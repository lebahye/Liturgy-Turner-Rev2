#!/usr/bin/env node
/**
 * Discover candidate new Armenian words from known liturgy recordings.
 *
 * Method (offline, no Whisper):
 * 1) Use page timestamps + liturgy text database
 * 2) Assume pages up to each recording duration were sung
 * 3) Extract Armenian words from those pages
 * 4) Remove words already in armenian-phonetic-dict.json
 * 5) Rank by frequency and overlap across recordings
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const textDb = JSON.parse(fs.readFileSync(path.join(__dirname, 'training-data/text-matcher-db.json'), 'utf8'));
const timestamps = JSON.parse(fs.readFileSync(path.join(__dirname, 'training-data/page-timestamps-mapped.json'), 'utf8'));
const baseDict = JSON.parse(fs.readFileSync(path.join(__dirname, 'training-data/armenian-phonetic-dict.json'), 'utf8'));

const knownWords = new Set(Object.keys(baseDict).map(w => w.toLowerCase()));

// Conservative durations from existing project notes/scripts
const recordings = [
  { name: 'youtube-liturgy.wav', durationSec: 83 * 60 },
  { name: 'youtube-liturgy-2.wav', durationSec: 68 * 60 },
];

const stopWords = new Set([
  'դպր', 'սրկ', 'քհն', 'էջ',
  'կանգնիլ', 'նստիլ', 'ոտքի',
]);

const pageToTimestamp = new Map(
  (timestamps.pages || []).map((p) => [Number(p.pageNumber), Number(p.timestamp)])
);

function extractArmenianWords(text) {
  return (text.match(/[Ա-և]+/g) || [])
    .map((w) => w.toLowerCase())
    .filter((w) => w.length >= 3 && !stopWords.has(w));
}

function collectForDuration(durationSec) {
  const freq = new Map();
  const pagesCovered = [];

  for (const page of textDb.pages || []) {
    const pageNum = Number(page.pageNumber);
    const ts = pageToTimestamp.get(pageNum);
    if (typeof ts !== 'number' || ts > durationSec) continue;

    pagesCovered.push(pageNum);
    const words = extractArmenianWords(page.armenianText || '');

    for (const w of words) {
      freq.set(w, (freq.get(w) || 0) + 1);
    }
  }

  return { freq, pagesCovered: [...new Set(pagesCovered)].sort((a, b) => a - b) };
}

const perRecording = [];
for (const rec of recordings) {
  const { freq, pagesCovered } = collectForDuration(rec.durationSec);
  const missing = [...freq.entries()]
    .filter(([w]) => !knownWords.has(w))
    .sort((a, b) => b[1] - a[1]);

  perRecording.push({
    ...rec,
    pagesCovered,
    missing,
  });
}

const [r1, r2] = perRecording;
const overlap = [];
for (const [w, c1] of r1.missing) {
  const c2 = r2.freq?.get?.(w) || (r2.missing.find(([x]) => x === w)?.[1] ?? 0);
  if (c2 > 0) overlap.push([w, c1 + c2, c1, c2]);
}
overlap.sort((a, b) => b[1] - a[1]);

const report = {
  generatedAt: new Date().toISOString(),
  method: 'timestamp-aligned text inference from recordings',
  existingDictionarySize: knownWords.size,
  recordings: perRecording.map(r => ({
    name: r.name,
    durationSec: r.durationSec,
    pagesCovered: r.pagesCovered.length,
    missingWordCount: r.missing.length,
    topMissingWords: r.missing.slice(0, 80).map(([word, count]) => ({ word, count })),
  })),
  overlapTopMissingWords: overlap.slice(0, 120).map(([word, total, rec1Count, rec2Count]) => ({
    word,
    total,
    rec1Count,
    rec2Count,
  })),
};

const jsonOut = path.join(__dirname, 'NEW_WORDS_FROM_RECORDINGS.json');
fs.writeFileSync(jsonOut, JSON.stringify(report, null, 2));

const mdOut = path.join(__dirname, 'NEW_WORDS_FROM_RECORDINGS.md');
let md = '# New Candidate Words from Two Recordings\n\n';
md += '- Generated by `discover-new-words-from-recordings.mjs`\n';
md += '- Method: timestamp-aligned text inference (offline, no Whisper)\n';
md += `- Existing Armenian dictionary size: ${knownWords.size}\n\n`;

for (const r of report.recordings) {
  md += `## ${r.name}\n`;
  md += `- Duration assumption: ${Math.round(r.durationSec / 60)} min\n`;
  md += `- Pages covered: ${r.pagesCovered}\n`;
  md += `- Missing words found: ${r.missingWordCount}\n\n`;
  md += '| Armenian word | Count |\n|---|---:|\n';
  for (const row of r.topMissingWords.slice(0, 30)) {
    md += `| ${row.word} | ${row.count} |\n`;
  }
  md += '\n';
}

md += '## High-priority missing words (present in both recordings)\n\n';
md += '| Armenian word | Total | Rec1 | Rec2 |\n|---|---:|---:|---:|\n';
for (const row of report.overlapTopMissingWords.slice(0, 50)) {
  md += `| ${row.word} | ${row.total} | ${row.rec1Count} | ${row.rec2Count} |\n`;
}

fs.writeFileSync(mdOut, md);

console.log(`✅ Wrote ${jsonOut}`);
console.log(`✅ Wrote ${mdOut}`);
console.log(`📌 Overlap missing words: ${report.overlapTopMissingWords.length}`);
